export function formatExpectedIncomeText(
  lang: LanguageCode,
  year: number,
  monthIndex: number,
  dayOfMonth: number,
  mode: IncomeDayMode,
  value: number,
  isCustomOverride = false,
): string {
  const dow = new Date(year, monthIndex, dayOfMonth).getDay();
  const weekday = WEEKDAYS_SHORT_BY_LANG[lang][dow] ?? '';
  if (isCustomOverride) {
    if (lang === 'en') return `${weekday} ${dayOfMonth} (custom date)`;
    if (lang === 'pt') return `${weekday} ${dayOfMonth} (data específica)`;
    return `${weekday} ${dayOfMonth} (fecha puntual)`;
  }
  if (mode === 'business_day') {
    if (lang === 'en') return `Business day #${value} (${weekday} ${dayOfMonth})`;
    if (lang === 'pt') return `${value}º dia útil (${weekday} ${dayOfMonth})`;
    return `${value}° día hábil (${weekday} ${dayOfMonth})`;
  }
  if (lang === 'en') return `Day ${value} (${weekday} ${dayOfMonth})`;
  if (lang === 'pt') return `Dia ${value} (${weekday} ${dayOfMonth})`;
  return `Día ${value} (${weekday} ${dayOfMonth})`;
}

